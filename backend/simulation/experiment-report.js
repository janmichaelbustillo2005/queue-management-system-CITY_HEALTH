// Reproducible WPS-A versus WRR report for the Regular/Vulnerable experiments (research only).
// Usage (from backend/): node simulation/experiment-report.js [outDir] [replications] [baseSeed]
// Output: experiment-results.json (every summary and the default-seed runs) and
// experiment-results.md (tables). Same seeds, same files: nothing here is random beyond the seeds.
const fs = require("node:fs");
const path = require("node:path");
const { EXPERIMENTS, DEFAULT_COUNT, VULNERABLE_MIX, HIGHER_PRIORITY_MIX, HOURLY_PROFILE } = require("./experiment-scenarios");
const { ALGORITHM_IDS, CRITERIA, GROUP_LABELS, STARVATION_WINDOW, STARVATION_MIN_CALLS, runExperiment, replicate, formatValue } = require("./experiments");

// Scenario A and B at the default 100 patients, then heavier days for sensitivity, and the stress test.
const REPLICATED = [
  ["regular-majority", DEFAULT_COUNT], ["vulnerable-majority", DEFAULT_COUNT],
  ["regular-majority", 150], ["vulnerable-majority", 150], ["regular-majority", 200], ["vulnerable-majority", 200],
  ["sustained-arrivals", DEFAULT_COUNT]
];

function buildReport({ replications = 30, baseSeed = 20261029 } = {}) {
  return {
    replications, baseSeed, algorithms: ALGORITHM_IDS,
    replicated: REPLICATED.map(([scenario, count]) => replicate({ scenario, count, baseSeed, replications })),
    single: Object.keys(EXPERIMENTS).map((scenario) => {
      const r = runExperiment({ scenario, seed: baseSeed, count: DEFAULT_COUNT });
      return { scenario, seed: r.seed, count: r.count, profile: r.profile, rows: r.rows, ordering: r.ordering, findings: r.findings,
        tracked: Object.fromEntries(ALGORITHM_IDS.map((a) => [a, r.metrics[a].tracked])),
        byGroup: Object.fromEntries(ALGORITHM_IDS.map((a) => [a, r.metrics[a].byGroup])) };
    })
  };
}

// Counts are averaged across seeds, so they show one decimal like the minutes.
const ci = (s, unit) => (s == null ? "—" : `${unit === "count" ? s.mean.toFixed(1) : formatValue(s.mean, unit)} ± ${unit === "pct" ? `${(s.ci95 * 100).toFixed(1)}%` : s.ci95.toFixed(unit === "rate" ? 2 : 1)}`);

function toMarkdown(report) {
  const [A, B] = report.algorithms;
  const { replications, baseSeed } = report;
  const lines = ["# WPS-A versus WRR: Regular-majority and Vulnerable-majority experiments", "",
    "> SYNTHETIC DATA ONLY. Every workload parameter is an assumption (backend/simulation/experiment-scenarios.js),",
    "> not a City Health Office measurement. Both algorithms serve the identical workload for each seed, in the",
    "> same shared queue with three general doctors; only the choice of the next patient differs.", "",
    `Generated by \`node simulation/experiment-report.js\` — ${replications} seeds per experiment (${baseSeed}–${baseSeed + replications - 1}).`,
    "Values are mean ± 95% CI half-width across seeds; the last column counts the seeds in which each algorithm was better (as displayed; capacity measures within 1% are ties).", "",
    "## Workload assumptions", "",
    `- Vulnerable mix (share among Vulnerable patients, apportioned exactly): ${VULNERABLE_MIX.map(([f, w]) => `${f.join("+")} ${w}%`).join(", ")}.`,
    `- Stress mix: ${HIGHER_PRIORITY_MIX.map(([f, w]) => `${f.join("+")} ${w}%`).join(", ")} among Vulnerable; 15% Regular.`,
    `- Scenario A/B registrations per hour from 08:00 (relative weights): ${HOURLY_PROFILE.join(", ")}.`,
    `- Starvation evidence: still waiting at the last registration, after ${STARVATION_WINDOW} minutes in which every call (at least ${STARVATION_MIN_CALLS}) went to a later registration.`, ""];
  for (const exp of report.replicated) {
    const meta = EXPERIMENTS[exp.scenario];
    lines.push(`## ${meta.label} — ${exp.count} patients`, "", meta.description + ".", "",
      `Offered load ${ci(exp.offeredLoad, "rate")} × capacity; seeds with at least one overloaded hour: ${exp.overloadedRuns}/${exp.replications}; seeds in which both algorithms called everyone in the same order: ${exp.sameOrderRuns}/${exp.replications}.`, "",
      `| Measure | ${A} | ${B} | Better (${A} / ${B} / tie) |`, "|---|---|---|---|");
    for (const row of exp.rows) {
      lines.push(`| ${row.label} | ${ci(row.summary[A], row.unit)} | ${ci(row.summary[B], row.unit)} | ${row.lowerIsBetter == null ? "n/a" : `${row.better[A]} / ${row.better[B]} / ${row.better.tie}`} |`);
    }
    lines.push(`| Pairs where a later Regular was called before a Vulnerable patient | ${ci(exp.laterRegularAheadOfVulnerable[A], "count")} | ${ci(exp.laterRegularAheadOfVulnerable[B], "count")} | n/a |`, "",
      "Average and maximum wait by classification (minutes):", "", `| Classification | ${A} average | ${B} average | ${A} maximum | ${B} maximum |`, "|---|---|---|---|---|");
    for (const [group, v] of Object.entries(exp.byGroup)) {
      lines.push(`| ${GROUP_LABELS[group]} | ${ci(v[A].avg, "min")} | ${ci(v[B].avg, "min")} | ${ci(v[A].max, "min")} | ${ci(v[B].max, "min")} |`);
    }
    lines.push("");
  }
  lines.push(`# Default seed ${baseSeed}: single runs shown on the page`, "");
  for (const run of report.single) {
    const meta = EXPERIMENTS[run.scenario];
    lines.push(`## ${meta.label} — ${run.count} patients, seed ${run.seed}`, "", `| Measure | ${A} | ${B} | Better |`, "|---|---|---|---|");
    for (const row of run.rows) lines.push(`| ${row.label} | ${row.shown[0]} | ${row.shown[1]} | ${row.lowerIsBetter == null ? "n/a" : row.better || "tie"} |`);
    lines.push("", "Findings (generated from this run):", "", ...run.findings.lines.map((l) => `- ${l}`), "",
      "Criteria (metrics won in this run):", "", ...run.findings.criteria.map((c) => `- ${c.importance}: ${c.label} — ${A} ${c.wins[A]}, ${B} ${c.wins[B]}${c.leader ? ` (leans ${c.leader})` : " (even)"}`), "");
  }
  lines.push("## Evaluation criteria and relative importance", "", ...CRITERIA.map((c) => `- **${c.importance}: ${c.label}.** ${c.why}`), "",
    "No overall winner is declared: the two Primary criteria are in tension, and the choice depends on the weight the City Health Office gives to each.", "");
  return lines.join("\n");
}

if (require.main === module) {
  const outDir = path.resolve(process.argv[2] || "simulation-output");
  const replications = Number(process.argv[3] || 30);
  const baseSeed = Number(process.argv[4] || 20261029);
  const report = buildReport({ replications, baseSeed });
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "experiment-results.json"), JSON.stringify(report, null, 1));
  fs.writeFileSync(path.join(outDir, "experiment-results.md"), toMarkdown(report));
  console.log(`Wrote ${path.join(outDir, "experiment-results.md")} and experiment-results.json`);
}

module.exports = { buildReport, toMarkdown, REPLICATED };
