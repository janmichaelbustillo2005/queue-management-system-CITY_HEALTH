// Runs every scenario with every policy on identical seeded workloads, in both D1 dispatch modes,
// and writes results.
// Usage (from backend/): node simulation/run.js [outDir] [replications] [baseSeed]
// Output: results.json (all per-replication metrics and summaries) and results.md (tables).
const fs = require("node:fs");
const path = require("node:path");
const { generateWorkload, runSimulation, DOCTORS } = require("./engine");
const { POLICIES } = require("./policies");
const { SCENARIOS } = require("./scenarios");
const { dayMetrics, summarize } = require("./metrics");

const DISPATCH_MODES = ["service", "shared"];
const MODE_TITLES = {
  service: "Dispatch: service (fixed service-to-doctor mapping, three queues; current behavior)",
  shared: "Dispatch: shared (D1 Model A, provisional: general doctors take the head of one queue)"
};

function runAll({ replications = 30, baseSeed = 20261029, scenarios = SCENARIOS, dispatch = "service" } = {}) {
  const results = {};
  for (const [scenarioName, scenario] of Object.entries(scenarios)) {
    const perPolicy = Object.fromEntries(Object.keys(POLICIES).map((name) => [name, []]));
    for (let rep = 0; rep < replications; rep += 1) {
      const workload = generateWorkload(scenario, baseSeed + rep);   // identical for every policy and mode
      for (const [policyName, makePolicy] of Object.entries(POLICIES)) {
        perPolicy[policyName].push(dayMetrics(runSimulation(workload, makePolicy, { dispatch })));
      }
    }
    results[scenarioName] = { description: scenario.description, policies: {} };
    for (const [policyName, days] of Object.entries(perPolicy)) {
      const field = (fn) => summarize(days.map(fn));
      const groups = [...new Set(days.flatMap((d) => Object.keys(d.byGroup)))].sort();
      results[scenarioName].policies[policyName] = {
        patients: field((d) => d.patients),
        avgWait: field((d) => d.avgWait), p95Wait: field((d) => d.p95Wait), maxWait: field((d) => d.maxWait),
        jainFairness: field((d) => d.jainFairness), throughputPerHour: field((d) => d.throughputPerHour),
        makespanMinutes: field((d) => d.makespanMinutes),
        utilization: Object.fromEntries(DOCTORS.map((doc) => [doc, field((d) => d.utilization[doc])])),
        waitsOver60: field((d) => d.starvation.over60), waitsOver120: field((d) => d.starvation.over120),
        priorityInversions: field((d) => d.priorityInversions), regularBeforeProtected: field((d) => d.regularBeforeProtected),
        byGroup: Object.fromEntries(groups.map((g) => [g, {
          avgWait: field((d) => d.byGroup[g]?.avgWait), p95Wait: field((d) => d.byGroup[g]?.p95Wait), maxWait: field((d) => d.byGroup[g]?.maxWait)
        }])),
        replications: days
      };
    }
  }
  return results;
}

const fmt = (s, digits = 1) => (s == null ? "–" : `${s.mean.toFixed(digits)} ± ${s.ci95.toFixed(digits)}`);

function appendScenarios(lines, results) {
  for (const [scenario, { description, policies }] of Object.entries(results)) {
    lines.push(`## ${scenario}`, "", description, "",
      "| Policy | Avg wait | P95 wait | Max wait | Waits > 60 min (count) | Jain fairness | Throughput /h | Util. D1 / D2 / D3 | Lower-score-first decisions | Regular before waiting protected |",
      "|---|---|---|---|---|---|---|---|---|---|");
    for (const [name, m] of Object.entries(policies)) {
      const util = DOCTORS.map((d) => m.utilization[d].mean.toFixed(2)).join(" / ");
      lines.push(`| ${name} | ${fmt(m.avgWait)} | ${fmt(m.p95Wait)} | ${fmt(m.maxWait)} | ${fmt(m.waitsOver60)} | ${fmt(m.jainFairness, 3)} | ${fmt(m.throughputPerHour, 2)} | ${util} | ${fmt(m.priorityInversions)} | ${fmt(m.regularBeforeProtected)} |`);
    }
    const groups = [...new Set(Object.values(policies).flatMap((m) => Object.keys(m.byGroup)))].sort();
    lines.push("", "Average wait by priority group (minutes):", "", `| Policy | ${groups.join(" | ")} |`, `|---|${groups.map(() => "---").join("|")}|`);
    for (const [name, m] of Object.entries(policies)) lines.push(`| ${name} | ${groups.map((g) => fmt(m.byGroup[g]?.avgWait)).join(" | ")} |`);
    lines.push("", "Maximum wait by priority group (minutes):", "", `| Policy | ${groups.join(" | ")} |`, `|---|${groups.map(() => "---").join("|")}|`);
    for (const [name, m] of Object.entries(policies)) lines.push(`| ${name} | ${groups.map((g) => fmt(m.byGroup[g]?.maxWait)).join(" | ")} |`);
    lines.push("");
  }
}

function toMarkdown(byMode, { replications, baseSeed }) {
  const lines = ["# Scheduling simulation results", "",
    "> Both D1 dispatch modes are reported; neither is assumed to be the approved one. Workloads are SYNTHETIC",
    "> and every parameter is an assumption (simulation/scenarios.js): these are model results, not clinic",
    "> measurements. Rerun with observed clinic data before drawing conclusions about the real clinic.", "",
    `Generated by \`node simulation/run.js\` — ${replications} replications per scenario and mode, seeds ${baseSeed}–${baseSeed + replications - 1};`,
    "identical patients for every policy and mode within a seed. Values are mean ± 95% CI half-width, minutes unless stated.", ""];
  for (const [mode, results] of Object.entries(byMode)) {
    lines.push(`# ${MODE_TITLES[mode]}`, "");
    appendScenarios(lines, results);
  }
  return lines.join("\n");
}

if (require.main === module) {
  const outDir = path.resolve(process.argv[2] || "simulation-output");
  const replications = Number(process.argv[3] || 30);
  const baseSeed = Number(process.argv[4] || 20261029);
  const byMode = Object.fromEntries(DISPATCH_MODES.map((dispatch) => [dispatch, runAll({ replications, baseSeed, dispatch })]));
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "results.json"), JSON.stringify({ replications, baseSeed, byMode }, null, 1));
  fs.writeFileSync(path.join(outDir, "results.md"), toMarkdown(byMode, { replications, baseSeed }));
  console.log(`Wrote ${path.join(outDir, "results.md")} and results.json`);
}

module.exports = { runAll, toMarkdown, DISPATCH_MODES };
